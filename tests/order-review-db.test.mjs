import test from 'node:test';
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
test('RPC de revisão preserva dados e bloqueia alterações inválidas, não autorizadas ou concorrentes', async () => {
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth; create schema private;
create function auth.uid() returns uuid language sql as 'select nullif(current_setting(''test.user_id'',true),'''')::uuid';
create function private.user_has_role(text[]) returns boolean language sql as 'select current_setting(''test.writer'',true)=''true''';`);
await db.exec(readFileSync('supabase/migrations/001_initial_schema.sql','utf8').replace('create extension if not exists pgcrypto;', ''));
await db.exec(`alter table public.fulfillments add column customer_email text, add column omie_last_error text;
grant usage on schema auth,private to authenticated;
grant select,insert,update on public.fulfillments,public.recipients,public.delivery_addresses,public.audit_logs to authenticated;
create policy f on public.fulfillments to authenticated using(true) with check(true);
create policy r on public.recipients to authenticated using(true) with check(true);
create policy a on public.delivery_addresses to authenticated using(true) with check(true);
create policy l on public.audit_logs to authenticated using(true) with check(true);`);
await db.exec(readFileSync('supabase/migrations/20261117122202_review_order_editing.sql','utf8'));
const one = async q => (await db.query(q)).rows[0];
const r = await one(`insert into public.recipients(full_name) values('Nome original') returning id`);
const a = await one(`insert into public.delivery_addresses(recipient_id,postal_code,street,number,district,city,state) values('${r.id}','23088000','Rua original','1','Centro','Rj','RJ') returning id`);
const f = await one(`insert into public.fulfillments(recipient_id,delivery_address_id,status,idempotency_key,omie_last_error) values('${r.id}','${a.id}','order_pending','test','Erro anterior') returning *`);
await db.exec(`set role authenticated; select set_config('test.user_id','11111111-1111-4111-8111-111111111111',false); select set_config('test.writer','true',false);`);
const fields = {name:'Nome corrigido',email:'pedido@example.com',postal_code:'23088000',street:'Rua corrigida',number:'2',complement:'Casa 1',district:'Centro',city:'Rio de Janeiro',state:'RJ'};
const save = (version, value=fields) => db.query('select public.save_reviewed_fulfillment($1,$2,$3)',[f.id,version,JSON.stringify(value)]);
const originalVersion = f.updated_at;
for (const [key,value] of [['name','a'.repeat(61)],['street','a'.repeat(61)],['number','1'.repeat(11)],['complement','a'.repeat(61)],['district','a'.repeat(61)],['city','Rio/RJ'],['state','XX'],['email','bad'],['postal_code','123']]) {
  await assert.rejects(save(originalVersion,{...fields,[key]:value}),/INVALID_REVIEW_FIELDS/);
}
await db.exec(`select set_config('test.writer','false',false)`);
await assert.rejects(save(originalVersion),/FORBIDDEN/);
await db.exec(`select set_config('test.writer','true',false); select set_config('test.user_id','',false)`);
await assert.rejects(save(originalVersion),/AUTH_REQUIRED/);
await db.exec(`select set_config('test.user_id','11111111-1111-4111-8111-111111111111',false)`);
await save(originalVersion);
const after = await one(`select * from public.fulfillments where id='${f.id}'`);
assert.notEqual(after.delivery_address_id,a.id);
assert.equal(after.delivery_recipient_name,fields.name);
assert.equal(after.status,'order_pending');
assert.equal(after.omie_order_id,null);
assert.equal(after.omie_last_error,'Erro anterior');
assert.equal((await one(`select full_name from public.recipients where id='${r.id}'`)).full_name,'Nome original');
assert.equal((await one(`select street from public.delivery_addresses where id='${a.id}'`)).street,'Rua original');
assert.equal((await one(`select count(*)::int as n from public.audit_logs`)).n,1);
assert.equal((await one(`select validation_status from public.delivery_addresses where id='${after.delivery_address_id}'`)).validation_status,'pending');
await assert.rejects(save(originalVersion),/ORDER_CHANGED/);
await db.exec(`update public.fulfillments set omie_send_started_at=now() where id='${f.id}'`);
await assert.rejects(save(after.updated_at),/SEND_IN_PROGRESS/);
await db.exec(`update public.fulfillments set omie_send_started_at=null,omie_order_id=123 where id='${f.id}'`);
await assert.rejects(save(after.updated_at),/NOT_REVIEWABLE/);
await db.exec(`update public.fulfillments set omie_order_id=null,status='ready' where id='${f.id}'`);
await assert.rejects(save(after.updated_at),/NOT_REVIEWABLE/);
assert.equal((await one(`select count(*)::int as n from public.audit_logs`)).n,1);
assert.equal((await one(`select count(*)::int as n from public.delivery_addresses`)).n,2);
await db.close();
});
